// Service worker minimo: solo lo suficiente para que Chrome/Android
// ofrezca "Instalar app". No cachea datos de la planilla (siempre deben
// venir frescos desde Google Apps Script).
const CACHE_NAME = "patagonia-natural-shell-v1";
const APP_SHELL = ["/", "/manifest.webmanifest", "/icon-192.png", "/icon-512.png"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
      )
  );
  self.clients.claim();
});

// Network-first: intenta siempre traer la version mas nueva; si no hay
// internet, cae al cache (solo para el shell de la app, nunca para datos
// de la API de Apps Script, que son peticiones cross-origin distintas).
self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return; // deja pasar las llamadas a Apps Script tal cual

  event.respondWith(
    fetch(event.request)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        return res;
      })
      .catch(() => caches.match(event.request))
  );
});
